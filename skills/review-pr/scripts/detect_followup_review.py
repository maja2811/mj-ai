#!/usr/bin/env python3

from __future__ import annotations

import argparse
import fnmatch
import json
import re
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from typing import Any


BOT_LOGIN_PATTERNS = (
    "github-actions",
    "dependabot",
    "renovate",
    "bot",
    "ai-reviewer",
    "pr-reviewer",
)
AI_BODY_PATTERNS = (
    "**AI-Generated Review Notice:**",
    "AI-Generated Review Notice",
    "### Summary (≤120 words)",
    "### Summary (<=120 words)",
    "### Findings\n| # | Severity | Location | Comment |",
    "### Overall Recommendation",
    "AI assistant and may contain errors",
    "generated by an AI assistant",
    "This review was generated by AI",
)
SHA_RE = re.compile(r"\b[0-9a-f]{40}\b", re.IGNORECASE)
GITHUB_BLOB_SHA_RE = re.compile(r"github\.com/[^/]+/[^/]+/blob/([0-9a-f]{40})/", re.IGNORECASE)


def eprint(message: str) -> None:
    print(message, file=sys.stderr)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Detect the latest previous AI review from collected PR artifacts."
    )
    parser.add_argument("--manifest-path", required=True, help="Path to pr-manifest.json")
    parser.add_argument(
        "--output-path",
        help="Path for follow-up context JSON; defaults to <workspace>/followup-context.json",
    )
    parser.add_argument(
        "--previous-review-path",
        help="Path for previous AI review markdown; defaults to <workspace>/previous-review.md",
    )
    parser.add_argument(
        "--author-responses-path",
        help="Path for author responses markdown; defaults to <workspace>/author-responses.md",
    )
    parser.add_argument(
        "--diff-since-last-path",
        help="Path for incremental diff; defaults to <workspace>/diff-since-last.diff",
    )
    parser.add_argument(
        "--exclude",
        action="append",
        default=[],
        help="File path, basename, or glob pattern to exclude from incremental diff",
    )
    parser.add_argument("--json", action="store_true", help="Print context JSON to stdout")
    return parser


def require_gh() -> None:
    if shutil.which("gh") is None:
        raise SystemExit("GitHub CLI 'gh' is required when computing incremental diffs.")


def load_json(path_value: str | Path | None, default: Any) -> Any:
    if not path_value:
        return default
    path = Path(path_value).expanduser().resolve()
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")


def parse_datetime(value: str | None) -> datetime | None:
    if not value:
        return None
    try:
        return datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return None


def user_login(payload: dict[str, Any]) -> str:
    user = payload.get("user")
    return str((user or {}).get("login") or "") if isinstance(user, dict) else ""


def is_ai_comment(payload: dict[str, Any]) -> bool:
    login = user_login(payload).lower()
    if login.endswith("[bot]") or any(pattern in login for pattern in BOT_LOGIN_PATTERNS):
        return True

    body = str(payload.get("body") or "")
    return any(pattern in body for pattern in AI_BODY_PATTERNS)


def infer_commit_sha(body: str, explicit_sha: Any) -> tuple[str | None, str | None]:
    if isinstance(explicit_sha, str) and SHA_RE.fullmatch(explicit_sha):
        return explicit_sha, "github_metadata"

    blob_match = GITHUB_BLOB_SHA_RE.search(body)
    if blob_match:
        return blob_match.group(1), "github_blob_link"

    sha_match = SHA_RE.search(body)
    if sha_match:
        return sha_match.group(0), "body_sha"

    return None, None


def collect_candidates(
    issue_comments: list[Any], review_comments: list[Any], reviews: list[Any]
) -> list[dict[str, Any]]:
    candidates: list[dict[str, Any]] = []

    for comment in issue_comments:
        if not isinstance(comment, dict) or not is_ai_comment(comment):
            continue
        body = str(comment.get("body") or "")
        commit_sha, commit_source = infer_commit_sha(body, None)
        candidates.append(
            {
                "type": "issue_comment",
                "id": comment.get("id"),
                "body": body,
                "created_at": comment.get("created_at"),
                "commit_sha": commit_sha,
                "commit_sha_source": commit_source,
                "author_login": user_login(comment),
                "html_url": comment.get("html_url"),
            }
        )

    for comment in review_comments:
        if not isinstance(comment, dict) or not is_ai_comment(comment):
            continue
        body = str(comment.get("body") or "")
        commit_sha, commit_source = infer_commit_sha(body, comment.get("commit_id"))
        candidates.append(
            {
                "type": "review_comment",
                "id": comment.get("id"),
                "body": body,
                "created_at": comment.get("created_at"),
                "commit_sha": commit_sha,
                "commit_sha_source": commit_source,
                "author_login": user_login(comment),
                "html_url": comment.get("html_url"),
                "path": comment.get("path"),
                "line": comment.get("line"),
            }
        )

    for review in reviews:
        if not isinstance(review, dict) or not review.get("body") or not is_ai_comment(review):
            continue
        body = str(review.get("body") or "")
        commit_sha, commit_source = infer_commit_sha(body, review.get("commit_id"))
        candidates.append(
            {
                "type": "review",
                "id": review.get("id"),
                "body": body,
                "created_at": review.get("submitted_at"),
                "state": review.get("state"),
                "commit_sha": commit_sha,
                "commit_sha_source": commit_source,
                "author_login": user_login(review),
                "html_url": review.get("html_url"),
            }
        )

    candidates.sort(key=lambda item: item.get("created_at") or "", reverse=True)
    return candidates


def collect_author_responses(
    pr_author: str | None,
    since_value: str | None,
    issue_comments: list[Any],
    review_comments: list[Any],
) -> list[dict[str, Any]]:
    since_dt = parse_datetime(since_value)
    if not pr_author or not since_dt:
        return []

    responses: list[dict[str, Any]] = []
    for comment in issue_comments:
        if not isinstance(comment, dict) or is_ai_comment(comment):
            continue
        created_at = str(comment.get("created_at") or "")
        comment_dt = parse_datetime(created_at)
        if comment_dt and comment_dt > since_dt and user_login(comment) == pr_author:
            responses.append(
                {
                    "type": "comment",
                    "created_at": created_at,
                    "user": pr_author,
                    "body": comment.get("body") or "",
                    "html_url": comment.get("html_url"),
                }
            )

    for comment in review_comments:
        if not isinstance(comment, dict) or is_ai_comment(comment):
            continue
        created_at = str(comment.get("created_at") or "")
        comment_dt = parse_datetime(created_at)
        if comment_dt and comment_dt > since_dt and user_login(comment) == pr_author:
            responses.append(
                {
                    "type": "review_comment",
                    "created_at": created_at,
                    "user": pr_author,
                    "body": comment.get("body") or "",
                    "path": comment.get("path"),
                    "line": comment.get("line"),
                    "html_url": comment.get("html_url"),
                }
            )

    responses.sort(key=lambda item: item.get("created_at") or "")
    return responses


def matches_excluded_pattern(file_path: str | None, patterns: list[str]) -> bool:
    if not file_path:
        return False
    basename = file_path.split("/")[-1]
    return any(
        pattern == file_path
        or pattern == basename
        or fnmatch.fnmatch(file_path, pattern)
        or fnmatch.fnmatch(basename, pattern)
        for pattern in patterns
    )


def diff_path_from_header_line(line: str) -> str | None:
    if line.startswith("diff --git "):
        parts = line.split()
        if len(parts) >= 4:
            candidate = parts[3]
            return candidate[2:] if candidate.startswith("b/") else candidate
    if line.startswith("+++ b/"):
        return line[6:].strip()
    if line.startswith("--- a/"):
        return line[6:].strip()
    return None


def filter_unified_diff(diff_text: str, patterns: list[str]) -> str:
    patterns = [pattern.strip() for pattern in patterns if pattern and pattern.strip()]
    if not patterns:
        return diff_text

    output: list[str] = []
    current_block: list[str] = []
    current_excluded = False

    def flush() -> None:
        nonlocal current_block, current_excluded
        if current_block and not current_excluded:
            output.extend(current_block)
        current_block = []
        current_excluded = False

    for line in diff_text.splitlines(keepends=True):
        if line.startswith("diff --git "):
            flush()
            current_block = [line]
            current_excluded = matches_excluded_pattern(diff_path_from_header_line(line), patterns)
            continue
        if current_block:
            path = diff_path_from_header_line(line)
            if path and matches_excluded_pattern(path, patterns):
                current_excluded = True
            current_block.append(line)
        else:
            output.append(line)
    flush()
    return "".join(output)


def run_gh_diff(owner: str, repo: str, base_sha: str, head_sha: str) -> str:
    require_gh()
    command = [
        "gh",
        "api",
        f"repos/{owner}/{repo}/compare/{base_sha}...{head_sha}",
        "-H",
        "Accept: application/vnd.github.diff",
    ]
    try:
        result = subprocess.run(command, check=True, capture_output=True, text=True)
    except subprocess.CalledProcessError as exc:
        stderr = (exc.stderr or "").strip()
        stdout = (exc.stdout or "").strip()
        detail = stderr or stdout or f"exit code {exc.returncode}"
        raise RuntimeError(f"Command failed: {' '.join(command)}\n{detail}") from exc
    return result.stdout


def format_author_responses(responses: list[dict[str, Any]]) -> str:
    if not responses:
        return ""
    lines: list[str] = []
    for response in responses:
        if response.get("type") == "review_comment":
            location = f" on {response.get('path') or ''}:{response.get('line') or ''}"
            lines.append(f"[{response.get('created_at')}] Response{location}: {response.get('body')}")
        else:
            lines.append(f"[{response.get('created_at')}] Response: {response.get('body')}")
    return "\n".join(lines) + "\n"


def main() -> int:
    args = build_parser().parse_args()
    manifest_path = Path(args.manifest_path).expanduser().resolve()
    manifest = load_json(manifest_path, {})
    workspace = Path(manifest.get("workspace") or manifest_path.parent).expanduser().resolve()

    output_path = Path(args.output_path).expanduser().resolve() if args.output_path else workspace / "followup-context.json"
    previous_review_path = Path(args.previous_review_path).expanduser().resolve() if args.previous_review_path else workspace / "previous-review.md"
    author_responses_path = Path(args.author_responses_path).expanduser().resolve() if args.author_responses_path else workspace / "author-responses.md"
    diff_since_last_path = Path(args.diff_since_last_path).expanduser().resolve() if args.diff_since_last_path else workspace / "diff-since-last.diff"

    issue_comments = load_json(manifest.get("issue_comments_path"), [])
    review_comments = load_json(manifest.get("review_comments_path"), [])
    reviews = load_json(manifest.get("reviews_path"), [])
    pr_data = load_json(manifest.get("pr_json_path"), {})

    if not isinstance(issue_comments, list):
        issue_comments = []
    if not isinstance(review_comments, list):
        review_comments = []
    if not isinstance(reviews, list):
        reviews = []

    candidates = collect_candidates(issue_comments, review_comments, reviews)
    previous = candidates[0] if candidates else None
    head_sha = manifest.get("head_sha")
    excluded_patterns = [pattern.strip() for pattern in (manifest.get("excluded_patterns") or []) if str(pattern).strip()]
    excluded_patterns.extend(pattern.strip() for pattern in args.exclude if pattern.strip())
    excluded_patterns = sorted(set(excluded_patterns))

    context: dict[str, Any] = {
        "review_type": "INITIAL",
        "previous_review_found": False,
        "previous_review": None,
        "previous_review_path": None,
        "author_responses": [],
        "author_responses_path": None,
        "diff_since_last_path": None,
        "diff_since_last_available": False,
        "candidate_count": len(candidates),
        "candidate_summaries": [
            {
                "type": item.get("type"),
                "id": item.get("id"),
                "created_at": item.get("created_at"),
                "commit_sha": item.get("commit_sha"),
                "author_login": item.get("author_login"),
                "html_url": item.get("html_url"),
            }
            for item in candidates
        ],
    }

    if previous:
        body = str(previous.get("body") or "")
        write_text(previous_review_path, body)
        pr_author = None
        if isinstance(pr_data, dict) and isinstance(pr_data.get("user"), dict):
            pr_author = pr_data["user"].get("login")
        responses = collect_author_responses(pr_author, previous.get("created_at"), issue_comments, review_comments)
        write_text(author_responses_path, format_author_responses(responses))

        previous_commit = previous.get("commit_sha")
        diff_available = False
        if previous_commit and head_sha and previous_commit != head_sha:
            diff_text = run_gh_diff(str(manifest.get("owner")), str(manifest.get("repo")), str(previous_commit), str(head_sha))
            write_text(diff_since_last_path, filter_unified_diff(diff_text, excluded_patterns))
            diff_available = True
        elif previous_commit and head_sha and previous_commit == head_sha:
            write_text(diff_since_last_path, "")
            diff_available = True

        context.update(
            {
                "review_type": "FOLLOWUP",
                "previous_review_found": True,
                "previous_review": {key: value for key, value in previous.items() if key != "body"},
                "previous_review_path": str(previous_review_path),
                "author_responses": responses,
                "author_responses_path": str(author_responses_path),
                "diff_since_last_path": str(diff_since_last_path) if diff_available else None,
                "diff_since_last_available": diff_available,
                "head_sha": head_sha,
                "excluded_patterns": excluded_patterns,
            }
        )

    write_json(output_path, context)
    if args.json:
        print(json.dumps(context, indent=2))
    else:
        print(f"Follow-up context: {output_path}")
        print(f"review_type: {context['review_type']}")
        if context["previous_review_found"]:
            print(f"previous_review_path: {context['previous_review_path']}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        eprint(str(exc))
        raise
