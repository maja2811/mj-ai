#!/usr/bin/env python3

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any


DEFAULT_MODEL = "GPT-5.5"


def eprint(message: str) -> None:
    print(message, file=sys.stderr)


def default_template_path() -> Path:
    return Path(__file__).resolve().parents[1] / "references" / "final-review-template.md"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Render final PR review markdown from a body-only review and template."
    )
    parser.add_argument("--body-path", required=True, help="Body-only review markdown path")
    parser.add_argument("--output-path", required=True, help="Final rendered markdown path")
    parser.add_argument(
        "--template-path",
        default=str(default_template_path()),
        help="Markdown template path",
    )
    parser.add_argument(
        "--checklist-manifest-path",
        help="Checklist manifest JSON path from fetch_latest_checklist.py",
    )
    parser.add_argument(
        "--checklist-url",
        help="Checklist URL override; defaults to checklist manifest html_url",
    )
    parser.add_argument(
        "--model",
        default=DEFAULT_MODEL,
        help=f"Model display name for rendered markdown (default: {DEFAULT_MODEL})",
    )
    parser.add_argument("--json", action="store_true", help="Print render manifest JSON")
    return parser


def load_json(path_value: str | None) -> dict[str, Any]:
    if not path_value:
        return {}
    path = Path(path_value).expanduser().resolve()
    if not path.exists():
        return {}
    payload = json.loads(path.read_text(encoding="utf-8"))
    return payload if isinstance(payload, dict) else {}


def strip_generated_preamble(body: str) -> str:
    lines = body.splitlines()
    first_heading = None
    for index, line in enumerate(lines):
        if line.startswith("### "):
            first_heading = index
            break
    if first_heading is None:
        return body.strip() + "\n"

    leading = "\n".join(lines[:first_heading])
    if (
        "AI-Generated Review Notice" in leading
        or "**Used model:**" in leading
        or "This review was generated by" in leading
    ):
        return "\n".join(lines[first_heading:]).strip() + "\n"
    return body.strip() + "\n"


def validate_body(body: str) -> None:
    if not re.search(r"^###\s+", body, flags=re.MULTILINE):
        raise RuntimeError("Review body must contain the expected markdown section headings.")


def main() -> int:
    args = build_parser().parse_args()
    body_path = Path(args.body_path).expanduser().resolve()
    output_path = Path(args.output_path).expanduser().resolve()
    template_path = Path(args.template_path).expanduser().resolve()

    body = strip_generated_preamble(body_path.read_text(encoding="utf-8"))
    validate_body(body)
    template = template_path.read_text(encoding="utf-8")
    checklist_manifest = load_json(args.checklist_manifest_path)
    checklist_url = args.checklist_url or checklist_manifest.get("html_url")
    if not checklist_url:
        raise RuntimeError("Checklist URL is required for final review rendering.")

    rendered = (
        template.replace("{{MODEL}}", args.model)
        .replace("{{CHECKLIST_URL}}", str(checklist_url))
        .replace("{{BODY}}", body.strip())
        .rstrip()
        + "\n"
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(rendered, encoding="utf-8")

    manifest = {
        "body_path": str(body_path),
        "output_path": str(output_path),
        "template_path": str(template_path),
        "checklist_url": str(checklist_url),
        "model": args.model,
    }
    if args.json:
        print(json.dumps(manifest, indent=2))
    else:
        print(f"Rendered review: {output_path}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        eprint(str(exc))
        raise
